"""
Shadowprint S2 Dynamic Prober: Linux strace Syscall Parser.
Owner: Gaurang Udgirkar [G]

Parses /obs/strace.log output generated by:
  strace -f -e trace=openat,connect,execve -o /obs/strace.log
Extracts normalized file accesses, network connections, and process executions.
Computes canonical Layer 3 behavior_hash for Engine S3.
"""

import re
import json
import hashlib
from typing import Dict, Any, List, Set, Tuple, Optional
from shadowprint.models import BehaviorTuple

# Regex patterns for strace output lines
OPENAT_PATTERN = re.compile(r'openat\([^,]+,\s*"([^"]+)"')
CONNECT_IP_PATTERN = re.compile(r'connect\([^,]+,\s*\{sa_family=AF_INET(?:6)?,\s*(?:sin6?_port=htons\((\d+)\),\s*)?sin6?_addr=inet_addr\("([^"]+)"\)')
CONNECT_UNIX_PATTERN = re.compile(r'connect\([^,]+,\s*\{sa_family=AF_UNIX,\s*sun_path="([^"]+)"')
EXECVE_PATTERN = re.compile(r'execve\("([^"]+)",\s*\[([^\]]*)\]')

# Standard benign paths to filter out Python runtime noise
BENIGN_PATH_PREFIXES = (
    "/usr/local/lib/python",
    "/usr/lib/python",
    "/lib/x86_64-linux-gnu",
    "/usr/lib/x86_64-linux-gnu",
    "/etc/ld.so",
    "/usr/share/locale",
    "/usr/lib/locale",
    "/etc/ssl/certs",
    "/usr/local/pyvenv",
)


class SyscallParser:
    """Parses strace log files into structured runtime behaviors."""

    @staticmethod
    def is_application_path(path: str) -> bool:
        """Filters out standard Python runtime and dynamic linker files."""
        if any(path.startswith(prefix) for prefix in BENIGN_PATH_PREFIXES):
            return False
        # Ignore shared library caching
        if path.endswith(".so") or path.endswith(".so.1") or path.endswith(".pyc"):
            return False
        return True

    @classmethod
    def parse_log(cls, log_content: str, tool_name: str = "__server__") -> BehaviorTuple:
        """
        Parses strace log text and returns a normalized BehaviorTuple.
        """
        openat_paths: Set[str] = set()
        connect_addrs: Set[str] = set()
        execve_cmds: Set[str] = set()
        canary_touched = False

        for line in log_content.splitlines():
            line = line.strip()
            if not line:
                continue

            # 1. Parse openat(..., "filepath", ...)
            open_match = OPENAT_PATTERN.search(line)
            if open_match:
                filepath = open_match.group(1)
                if "canary" in filepath.lower() or filepath.startswith("/tmp/canary"):
                    canary_touched = True
                if cls.is_application_path(filepath):
                    openat_paths.add(filepath)

            # 2. Parse connect(..., AF_INET, ...)
            conn_match = CONNECT_IP_PATTERN.search(line)
            if conn_match:
                port = conn_match.group(1) or "unknown"
                ip = conn_match.group(2)
                connect_addrs.add(f"{ip}:{port}")
            else:
                unix_match = CONNECT_UNIX_PATTERN.search(line)
                if unix_match:
                    connect_addrs.add(f"unix:{unix_match.group(1)}")

            # 3. Parse execve("binary", ["cmd", ...])
            exec_match = EXECVE_PATTERN.search(line)
            if exec_match:
                binary = exec_match.group(1)
                raw_args = exec_match.group(2)
                # Ignore initial python invocation of the server itself
                if not binary.endswith("python3") and not binary.endswith("python"):
                    execve_cmds.add(f"{binary} {raw_args}".strip())

        # Canonical behavior_hash (Layer 3)
        sorted_openat = sorted(openat_paths)
        sorted_connect = sorted(connect_addrs)
        sorted_execve = sorted(execve_cmds)

        canonical_data = {
            "tool_name": tool_name,
            "openat": sorted_openat,
            "connect": sorted_connect,
            "execve": sorted_execve,
        }
        raw_json = json.dumps(canonical_data, sort_keys=True, separators=(",", ":"))
        behavior_hash = hashlib.sha256(raw_json.encode("utf-8")).hexdigest()

        return BehaviorTuple(
            tool_name=tool_name,
            openat_paths=sorted_openat,
            connect_addrs=sorted_connect,
            execve_cmds=sorted_execve,
            canary_touched=canary_touched,
            behavior_hash=behavior_hash,
        )
